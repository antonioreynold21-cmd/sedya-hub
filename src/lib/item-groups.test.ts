import { strict as a } from 'node:assert';
import { groupOrderItems } from './item-groups';
import { calculateItemTotal, calculateSales } from './sales';
type I = { item_name: string; outlet_name: string|null; section_name: string|null; section_rank: number|null; position: number; qty: number; price: number; unit: string; discount_type: 'percent'|'amount'; discount_value: number };
let p = 0;
const mk = (o: string|null, s: string|null, r: number|null, price = 1000, d = 0): I => ({ item_name: `i${p}`, outlet_name: o, section_name: s, section_rank: r, position: p++, qty: 2, price, unit: 'kg', discount_type: 'percent', discount_value: d });
a.deepEqual(groupOrderItems([mk(null, null, null), mk(null, null, null)]), { legacy: true });
const items = [mk('A', 'Bakery', 4), mk('A', 'Others', 3), mk('A', 'Bar', 2, 500, 10), mk('B', 'Kitchen', 1), mk('A', 'Kitchen', 1), mk('A', 'Pastry', 5), mk('A', null, null), mk('A', 'kitchen', 1)];
const g = groupOrderItems(items);
if (g.legacy) throw new Error('not legacy');
a.deepEqual(g.outlets.map(o => o.outlet), ['A', 'B']);
const A = g.outlets[0]!;
a.deepEqual(A.sections.map(s => s.name), ['Kitchen', 'Bar', 'Others', 'Bakery', 'Pastry']);
a.equal(A.sections.find(s => s.name === 'Others')!.items.length, 2);
a.equal(A.sections[0]!.items.length, 2);
a.ok(A.sections.every(s => s.items.length > 0));
const nos = g.outlets.flatMap(o => o.sections.flatMap(s => s.items.map(i => i.no)));
a.deepEqual(nos, [1, 2, 3, 4, 5, 6, 7, 8]);
const sum = g.outlets.flatMap(o => o.sections).reduce((t, s) => t + s.subtotal, 0);
a.equal(sum, items.reduce((t, i) => t + calculateItemTotal(i), 0));
const c = calculateSales(items, 'percent', 0, false, 0);
a.equal(sum, c.subtotal - c.itemDiscount);
const one = groupOrderItems([mk('X', 'Bar', 2), mk('X', 'Kitchen', 1)]);
if (one.legacy) throw new Error('x');
a.equal(one.outlets.length, 1);
a.deepEqual(one.outlets[0]!.sections.map(s => s.name), ['Kitchen', 'Bar']);
const nul = groupOrderItems([mk(null, 'Bar', 2)]);
if (nul.legacy) throw new Error('x');
a.equal(nul.outlets[0]!.outlet, null);
console.log('PASS: item-groups');
